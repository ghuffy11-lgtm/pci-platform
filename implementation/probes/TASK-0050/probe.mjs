// WHAT THIS PROBE IS
//   An enumeration of the E4 surfaces reachable through ONE test subject — the subject every
//   Shape-1 measurement in §4.11, §4.12 and §4.14 was taken on — followed, for every surface
//   found obtainable, by §4.15's adversity probe and its C1–C4 conditions.
