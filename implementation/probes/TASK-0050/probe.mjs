hr('S6 — OTHER SUBJECTS REACHABLE WITHOUT AN INSTALL (read-only enumeration)');

const ENGINE_HINTS = /sqlite|duckdb|libsql|postgres|pg$|mysql|lmdb|leveldb|rocksdb|lucene|tantivy|meilisearch|typesense|elastic|opensearch|orama|flexsearch|minisearch|lunr/i;
const searchRoots = [
  { label: 'repository node_modules', path: join(process.cwd(), 'node_modules') },
  { label: 'npm global node_modules', path: join(process.env.APPDATA ?? '', 'npm', 'node_modules') },
];
for (const root of searchRoots) {
  say('');
  say(`${root.label}: ${root.path}`);
  if (!root.path || !existsSync(root.path)) { say('   NOT PRESENT'); continue; }
  const entries = attempt(() => readdirSync(root.path).filter(n => !n.startsWith('.')));
  if (!entries.ok) { say(`   unreadable — ${entries.error}`); continue; }
  say(`   ${entries.value.length} package(s)`);
  const hits = entries.value.filter(n => ENGINE_HINTS.test(n));
  say(`   engine/index-shaped packages: ${hits.length ? hits.join(', ') : 'NONE'}`);
}

sub('built-in bindings this runtime carries, enumerated from the runtime itself');
const builtins = (await import('node:module')).builtinModules
  .filter(m => /sql|db|storage/i.test(m));
say(`   database-shaped built-ins: ${builtins.length ? builtins.join(', ') : 'NONE'}`);
say(`   -> node:sqlite is the only database engine this runtime supplies without an install.`);

sub('the extension path, named so it is not silently ignored');
const hasLoadExt = typeof db.loadExtension === 'function' || typeof db.enableLoadExtension === 'function';
say(`   DatabaseSync exposes loadExtension/enableLoadExtension: ${hasLoadExt ? 'YES' : 'NO'}`);
say(`   -> A loadable extension could in principle supply a trace surface. It would require a`);
say(`      COMPILED BINARY that is not present. That is an INSTALL, which TASK-0050's stop`);
say(`      conditions forbid: it is a BLOCKER to record, not a problem to solve locally.`);

// =============================================================================================
// S7 — Summary. Findings only; no verdict is invented here and none is upgraded.
// =============================================================================================
hr('S7 — SUMMARY OF WHAT WAS OBSERVED (findings only — verdicts belong to the record, not the probe)');

say(`subject                       : SQLite ${ver.v} via node:sqlite on Node ${process.version}`);
say(`log/trace/profile members     : ${classHits.length ? [...new Set(classHits)].join(', ') : 'NONE'}`);
say(`tracing pragmas INERT         : ${inertCount} of ${pragmaRows.length} (indistinguishable from the F15 control)`);
say(`reachable engine surfaces     : ${obtainable.length ? obtainable.map(c => c.name).join(', ') : 'NONE'}`);
say('');
for (const f of surfaceFindings) {
  say(`   ${f.name.padEnd(16)} disarmed-silent=${String(f.disarmedSilent).padEnd(5)} param-hits=${String(f.paramHits).padEnd(4)} inline-hits=${String(f.inlineHits).padEnd(4)} entries=${f.entries}`);
}
say('');
say('CONTROLS (structurally separate — MSG-0156: never reported as a finding about the subject)');
say(`   nonexistent pragma  : set threw ${control.setThrew}, read threw ${control.readThrew}, rows ${control.readRows}`);
say(`   nonexistent vtab    : threw ${!vtabControl.ok}`);

db.close();

