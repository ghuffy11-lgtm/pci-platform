for (const flag of ['DEBUG', 'ENABLE_SQLLOG', 'ENABLE_STMT_SCANSTATUS', 'ENABLE_STMTVTAB',
                    'ENABLE_EXPLAIN_COMMENTS', 'ENABLE_DBPAGE_VTAB', 'ENABLE_DBSTAT_VTAB',
                    'ENABLE_BYTECODE_VTAB', 'OMIT_TRACE', 'ENABLE_NORMALIZE']) {
  const present = opts.some(o => o === flag || o === `SQLITE_${flag}`);
  say(`   ${flag.padEnd(26)} : ${present ? '*** PRESENT ***' : 'ABSENT'}`);
}

// =============================================================================================
// S3 — Tracing pragmas against the F15 CONTROL.
//      §4.12: SQLite silently ignores an unrecognised pragma, so "PRAGMA vdbe_trace=on returned
//      no error" is evidence of nothing. The control is a pragma that CERTAINLY does not exist;
//      a tracing pragma is believed only if it behaves DIFFERENTLY from it.
// =============================================================================================
hr('S3 — TRACING PRAGMAS AGAINST THE F15 NONEXISTENT-PRAGMA CONTROL');

function pragmaBehaviour(name) {
  const set = attempt(() => db.exec(`PRAGMA ${name} = 1`));
  const read = attempt(() => db.prepare(`PRAGMA ${name}`).all());
  return {
    setThrew: !set.ok, setError: set.error ?? null,
    readThrew: !read.ok, readError: read.error ?? null,
    readRows: read.ok ? JSON.stringify(read.value) : null,
  };
}

sub('CONTROL — kept structurally separate (MSG-0156: a control\'s finding is never a finding about the subject)');
const control = pragmaBehaviour(NONEXISTENT_PRAGMA);
say(`   PRAGMA ${NONEXISTENT_PRAGMA}`);
say(`      set threw : ${control.setThrew}${control.setError ? ' — ' + control.setError : ''}`);
say(`      read threw: ${control.readThrew}${control.readError ? ' — ' + control.readError : ''}`);
say(`      read rows : ${control.readRows}`);

sub('the tracing pragmas, each compared against that control');
const sig = (b) => `${b.setThrew}|${b.readThrew}|${b.readRows}`;
const controlSig = sig(control);
const pragmaRows = [];
for (const p of ['vdbe_trace', 'vdbe_listing', 'vdbe_addoptrace', 'vdbe_debug',
                 'parser_trace', 'sql_trace', 'stmt_scanstatus']) {
  const b = pragmaBehaviour(p);
  const identical = sig(b) === controlSig;
  pragmaRows.push({ p, identical });
  say(`   PRAGMA ${p.padEnd(18)} : ${identical ? 'IDENTICAL TO CONTROL -> INERT' : '*** DIFFERS FROM CONTROL -> INVESTIGATE ***'}   (set threw ${b.setThrew}, read rows ${b.readRows})`);
}
const inertCount = pragmaRows.filter(r => r.identical).length;
say('');
say(`SUMMARY S3 — ${inertCount} of ${pragmaRows.length} tracing pragmas are INERT (indistinguishable from a pragma that certainly does not exist).`);

// =============================================================================================
// S4 — Engine-emitted VIRTUAL TABLE surfaces. This is where this probe goes BEYOND §4.15:
//      §4.15 measured a statement TRACE (a callback), and found it adverse because it EXPANDS
//      the statement. A statement REGISTRY is a different surface of the same family, and
//      whether it expands is exactly the question the referral in the task file turns on.
// =============================================================================================
hr('S4 — ENGINE-EMITTED VIRTUAL-TABLE SURFACES (this is the class §4.15 did not measure)');

sub('module_list — what virtual table modules this build actually carries, enumerated');
const modList = attempt(() => db.prepare('PRAGMA module_list').all().map(r => Object.values(r)[0]).sort());
if (modList.ok) {
  say(`   modules (${modList.value.length}): ${modList.value.join(', ')}`);
  for (const m of ['sqlite_stmt', 'bytecode', 'tables_used', 'dbstat', 'sqlite_dbpage', 'stmt']) {
    say(`   ${m.padEnd(16)} : ${modList.value.includes(m) ? '*** PRESENT ***' : 'ABSENT'}`);
  }
} else {
  say(`   PRAGMA module_list unavailable — ${modList.error}`);
}

sub('CONTROL — a virtual table that certainly does not exist, kept structurally separate');
const vtabControl = attempt(() => db.prepare(`SELECT * FROM ${NONEXISTENT_VTAB}`).all());
say(`   SELECT * FROM ${NONEXISTENT_VTAB}`);
say(`      threw : ${!vtabControl.ok}${vtabControl.ok ? '' : ' — ' + vtabControl.error}`);
say(`   -> a surface is believed present only if it behaves DIFFERENTLY from this.`);

// The candidate surfaces, each probed for existence the same way.
const CANDIDATE_SURFACES = [
  { name: 'sqlite_stmt', sql: 'SELECT * FROM sqlite_stmt',
    what: 'the engine\'s own registry of prepared statements — a statement surface, like §4.15\'s trace' },
  { name: 'bytecode', sql: 'SELECT * FROM bytecode(\'SELECT 1\')',
    what: 'the engine\'s compiled program for a statement' },
  { name: 'tables_used', sql: 'SELECT * FROM tables_used(\'SELECT 1\')',
    what: 'the tables a statement reads' },
  // NO LIMIT, deliberately. An adversity scan over one row of a surface is a scan of one row,
  // not of the surface — the whole surface must be searched for passage text or the "0 hits"
  // means nothing.
  { name: 'dbstat', sql: 'SELECT * FROM dbstat',
    what: 'page-level storage statistics (every row scanned, not a sample)' },
  { name: 'sqlite_dbpage', sql: 'SELECT pgno FROM sqlite_dbpage LIMIT 1',
    what: 'raw page images (a DURABILITY artefact, not a log — DA-1/N6 territory, recorded for completeness)' },
];

sub('candidate surfaces, each tried and each distinguished from the control');
const obtainable = [];
for (const c of CANDIDATE_SURFACES) {
  const r = attempt(() => db.prepare(c.sql).all());
  const distinguished = r.ok || !/no such table|no such module|no such function/i.test(r.error ?? '');
  say(`   ${c.name.padEnd(16)} : ${r.ok ? '*** REACHABLE ***' : 'NOT REACHABLE'}  ${r.ok ? `(${r.value.length} row(s))` : '— ' + r.error}`);
  say(`   ${''.padEnd(16)}   ${c.what}`);
  say(`   ${''.padEnd(16)}   differs from the nonexistent-vtab control: ${distinguished ? 'YES' : 'NO — same shape as a table that does not exist'}`);
  if (r.ok) obtainable.push(c);
}

// =============================================================================================
// S5 — For every REACHABLE surface: run it DISARMED before ARMED, then run §4.15's ADVERSITY
//      probe against it. §4.15's specific probe reproduced exactly: unauthorized text bound as
//      a PARAMETER. A surface that survives that is NOT thereby clean, so inlined text and the
//      other reachable path are tested too.
// =============================================================================================
hr('S5 — DISARMED BEFORE ARMED, THEN THE ADVERSITY PROBE (§4.15 reproduced, then extended)');

function scanForMarkers(rows) {
  const text = JSON.stringify(rows);
  return {
    param:  (text.match(new RegExp(MARK_PARAM, 'g'))  || []).length,
    inline: (text.match(new RegExp(MARK_INLINE, 'g')) || []).length,
    bytes: text.length,
  };
}

const surfaceFindings = [];

for (const c of obtainable) {
  sub(`SURFACE: ${c.name}`);

  // --- DISARMED: the surface read on a connection where no marker-bearing statement has ever
  //     been prepared. If it is not silent, the instrument is voided for this run (§4.15).
  const clean = new DatabaseSync(':memory:');
  clean.exec('CREATE TABLE t (a)');
  const disarmedRead = attempt(() => clean.prepare(c.sql).all());
  const disarmed = disarmedRead.ok ? scanForMarkers(disarmedRead.value) : null;
  say(`   DISARMED (fresh connection, no unauthorized text has ever passed through it)`);
  say(`      readable        : ${disarmedRead.ok}${disarmedRead.ok ? '' : ' — ' + disarmedRead.error}`);
  if (disarmed) {
    say(`      rows            : ${disarmedRead.value.length}`);
    say(`      marker hits     : param ${disarmed.param}, inline ${disarmed.inline}`);
    say(`      silent?         : ${disarmed.param === 0 && disarmed.inline === 0 ? 'YES — instrument is valid for this run' : 'NO — INSTRUMENT VOIDED'}`);
  }
  clean.close();

  // --- ARMED path 1: §4.15's exact probe — unauthorized text bound as a PARAMETER.
  const armedDb = new DatabaseSync(':memory:');
  buildFixture(armedDb);
  const q1 = armedDb.prepare('SELECT id FROM chunk WHERE body = ?');
  const returned1 = q1.all(`${MARK_PARAM} body 7`);
  const armed1Read = attempt(() => armedDb.prepare(c.sql).all());
  const armed1 = armed1Read.ok ? scanForMarkers(armed1Read.value) : null;
  say(`   ARMED path 1 — unauthorized text bound as a PARAMETER (§4.15's exact probe)`);
  say(`      query           : SELECT id FROM chunk WHERE body = ?      [param = "${MARK_PARAM} body 7"]`);
  say(`      rows returned   : ${returned1.length}`);
  say(`      surface readable: ${armed1Read.ok}${armed1Read.ok ? '' : ' — ' + armed1Read.error}`);
  if (armed1) {
    say(`      surface rows    : ${armed1Read.value.length}`);
    say(`      marker hits     : *** param ${armed1.param} ***, inline ${armed1.inline}`);
    if (armed1.param > 0) {
      const sample = JSON.stringify(armed1Read.value).match(new RegExp('.{0,60}' + MARK_PARAM + '.{0,30}'));
      say(`      verbatim sample : ${sample ? sample[0] : '(n/a)'}`);
    }
  }

  // --- ARMED path 2: the same text INLINED. A surface that survives path 1 is not thereby clean.
  const inlineText = `${MARK_INLINE} body 7`;
  const q2 = attempt(() => armedDb.prepare(`SELECT id FROM chunk WHERE body = '${inlineText}'`).all());
  const armed2Read = attempt(() => armedDb.prepare(c.sql).all());
  const armed2 = armed2Read.ok ? scanForMarkers(armed2Read.value) : null;
  say(`   ARMED path 2 — the same text INLINED into the statement`);
  say(`      query           : SELECT id FROM chunk WHERE body = '${inlineText}'`);
  say(`      rows returned   : ${q2.ok ? q2.value.length : 'threw — ' + q2.error}`);
  say(`      surface readable: ${armed2Read.ok}${armed2Read.ok ? '' : ' — ' + armed2Read.error}`);
  if (armed2) {
    say(`      surface rows    : ${armed2Read.value.length}`);
    say(`      marker hits     : param ${armed2.param}, *** inline ${armed2.inline} ***`);
    if (armed2.inline > 0) {
      const sample = JSON.stringify(armed2Read.value).match(new RegExp('.{0,60}' + MARK_INLINE + '.{0,30}'));
      say(`      verbatim sample : ${sample ? sample[0] : '(n/a)'}`);
    }
  }

  // --- C4: does the surface record what the engine EXAMINED, or only the instruction?
  //     §4.15's numbers: 200 examined, 100 returned, 1 trace entry.
  const examined = 200;
  const returnedAll = armedDb.prepare("SELECT id FROM chunk WHERE scope = 'unauthorized'").all().length;
  const c4Read = attempt(() => armedDb.prepare(c.sql).all());
  say(`   C4 — instruction or examination?`);
  say(`      rows in fixture   : ${examined}   (100 authorized + 100 unauthorized)`);
  say(`      unauthorized rows : ${returnedAll}`);
  say(`      surface entries   : ${c4Read.ok ? c4Read.value.length : 'unreadable'}`);
  if (c4Read.ok && modList.ok && c.name === 'sqlite_stmt') {
    const cols = c4Read.value.length ? Object.keys(c4Read.value[0]) : [];
    say(`      surface columns   : ${cols.join(', ')}`);
    say(`      per-statement counters present: ${cols.filter(k => /nscan|nstep|nsort|naidx|run|reprep/.test(k)).join(', ') || 'none'}`);
    for (const row of c4Read.value) {
      say(`         [stmt] ${JSON.stringify(row)}`);
    }
  }

  surfaceFindings.push({
    name: c.name,
    disarmedSilent: disarmed ? (disarmed.param === 0 && disarmed.inline === 0) : null,
    paramHits: armed1 ? armed1.param : null,
    inlineHits: armed2 ? armed2.inline : null,
    entries: c4Read.ok ? c4Read.value.length : null,
  });

  armedDb.close();
}

