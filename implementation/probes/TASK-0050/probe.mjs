// WHAT THIS PROBE IS NOT
//   It selects, adopts, ranks, deploys, implements and clears nothing. The subject is an EVIDENCE
//   INSTRUMENT, not a candidate (MSG-0141). It changes no gate and no verdict. It installs
//   nothing, spawns no process, opens no socket, and writes only inside its own directory.
//
// TWO DISCIPLINES CARRIED FROM THE RECORD, NOT INVENTED HERE
//   1. F15 / §4.12 gap 1 — every instrument is run against a control that CERTAINLY does not
//      exist, because without one "the instrument reported nothing" and "the instrument was never
