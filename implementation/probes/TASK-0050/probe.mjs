//      is enumerated and never assumed.
// =============================================================================================
hr('S0 — SUBJECT IDENTITY (engine build and language binding stated separately)');

const db = new DatabaseSync(':memory:');
buildFixture(db);

const ver = db.prepare('SELECT sqlite_version() AS v, sqlite_source_id() AS s').get();
say(`language binding      : node:sqlite (Node.js built-in)`);
say(`runtime               : Node ${process.version}  (${process.platform} ${process.arch})`);
