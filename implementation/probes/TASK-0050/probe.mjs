// ---------------------------------------------------------------------------------------------
// Markers. Two of them, deliberately distinct, so that a hit can be attributed to the path that
// produced it rather than to "the probe used a marker somewhere".
// ---------------------------------------------------------------------------------------------
const MARK_PARAM  = 'ZZ-UNAUTHORIZED-PASSAGE-TEXT-ZZ';  // §4.15's marker, bound as a PARAMETER
const MARK_INLINE = 'ZZ-UNAUTH-INLINE-TEXT-ZZ';         // the same text path, INLINED instead
const NONEXISTENT_PRAGMA = 'zzz_task_0050_pragma_that_certainly_does_not_exist';
const NONEXISTENT_VTAB   = 'zzz_task_0050_vtab_that_certainly_does_not_exist';

const out = [];
const say = (s = '') => { out.push(s); console.log(s); };
const hr  = (t) => { say(''); say('='.repeat(94)); say(t); say('='.repeat(94)); };
const sub = (t) => { say(''); say('--- ' + t + ' ' + '-'.repeat(Math.max(0, 88 - t.length))); };

function attempt(fn) {
  try { return { ok: true, value: fn() }; }
  catch (e) { return { ok: false, error: `${e.name}: ${e.message}` }; }
}

// ---------------------------------------------------------------------------------------------
// Fixture — §4.15's shape: 200 rows, 100 of them unauthorized and carrying the marker.
// The counts matter: §4.15 reported "200 examined, 100 returned, 1 trace entry", which is the
// C4 observation. This probe must be able to make the same comparison.
// ---------------------------------------------------------------------------------------------
function buildFixture(db) {
  db.exec(`CREATE TABLE chunk (id INTEGER PRIMARY KEY, scope TEXT NOT NULL, body TEXT NOT NULL)`);
  const ins = db.prepare(`INSERT INTO chunk (id, scope, body) VALUES (?, ?, ?)`);
  for (let i = 0; i < 100; i++) ins.run(i + 1, 'authorized', `authorized body ${i}`);
  for (let i = 0; i < 100; i++) ins.run(i + 101, 'unauthorized', `${MARK_PARAM} body ${i}`);
  db.exec(`CREATE INDEX idx_chunk_body ON chunk(body)`);
}

hr('TASK-0050 · E4 surface enumeration on the Shape-1 subject · GAP-B');
say(`generated by implementation/probes/TASK-0050/probe.mjs`);
say(`no install · no subprocess · no network · in-memory database only`);

