say(`engine source id      : ${ver.s}`);
say(`database location     : ${JSON.stringify(attempt(() => db.location()).value ?? null)}  (":memory:" — no file, so no engine-written artefact to read)`);

// =============================================================================================
// S1 — The surface, ENUMERATED rather than assumed. §4.15 enumerated 42 public Connection names
//      and named the 3 that were present; this does the same for this binding's classes.
// =============================================================================================
hr('S1 — THE SURFACE, ENUMERATED RATHER THAN ASSUMED');

const sqliteMod = await import('node:sqlite');
const LOGGISH = /trace|log|profile|scanstat|authoriz|progress|hook|callback|debug|explain|instrument/i;

function enumerateNames(label, obj) {
  if (!obj) { say(`${label}: NOT PRESENT`); return []; }
  const proto = typeof obj === 'function' ? obj.prototype : Object.getPrototypeOf(obj);
  const names = new Set();
  for (const n of Object.getOwnPropertyNames(obj)) names.add(n);
  if (proto) for (const n of Object.getOwnPropertyNames(proto)) names.add(n);
  const list = [...names].filter(n => !['length', 'name', 'prototype', 'constructor'].includes(n)).sort();
  const hits = list.filter(n => LOGGISH.test(n));
  say(`${label}`);
  say(`   members (${list.length}): ${list.join(', ') || '(none)'}`);
  say(`   log/trace/profile-shaped members: ${hits.length ? hits.join(', ') : 'NONE'}`);
  return hits;
}

sub('module exports');
say(`node:sqlite exports (${Object.keys(sqliteMod).length}): ${Object.keys(sqliteMod).sort().join(', ')}`);

const classHits = [];
sub('class surfaces');
for (const name of ['DatabaseSync', 'StatementSync', 'Session', 'StatementResultingChanges']) {
  classHits.push(...enumerateNames(`${name}`, sqliteMod[name]));
}
sub('live instance surfaces (a class may expose nothing and an instance still carry a member)');
classHits.push(...enumerateNames('db (live DatabaseSync instance)', db));
const liveStmt = db.prepare('SELECT id FROM chunk WHERE scope = ?');
classHits.push(...enumerateNames('stmt (live StatementSync instance)', liveStmt));

sub('the specific C-API entry points E4 would need, each checked by NAME rather than assumed');
const CAPI = ['sqlite3_trace_v2', 'trace', 'traceV2', 'setTrace', 'profile', 'setProfile',
              'config_log', 'configLog', 'setLogger', 'log',
              'stmt_scanstatus', 'scanstatus', 'setAuthorizer', 'authorizer',
              'setProgressHandler', 'progressHandler', 'setUpdateHook', 'updateHook',
              'commitHook', 'rollbackHook', 'preupdateHook'];
const dbAll = new Set([...Object.getOwnPropertyNames(sqliteMod.DatabaseSync.prototype),
                       ...Object.getOwnPropertyNames(db)]);
for (const n of CAPI) say(`   ${n.padEnd(22)} : ${dbAll.has(n) ? '*** PRESENT ***' : 'ABSENT'}`);

say('');
say(`SUMMARY S1 — log/trace/profile-shaped members found anywhere on this binding: ${classHits.length ? [...new Set(classHits)].join(', ') : 'NONE'}`);

// =============================================================================================
// S2 — The build. §4.15 reported 43 compile options and named the three absences that matter.
