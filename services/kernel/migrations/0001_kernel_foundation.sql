-- =============================================================================
-- Runtime role grants
--
-- The runtime role (pci_app) is deliberately NOT the owner and must NOT hold BYPASSRLS or
-- SUPERUSER, or layer 3 above becomes inert. Roles are created by
-- deploy/compose/initdb/00-roles.sql, which runs as the cluster superuser.
--
-- Append-only tables grant INSERT and SELECT only. Tamper-evidence required by SPEC-0006 and
-- security-architecture.md is enforced by privilege, not by convention.
-- =============================================================================

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pci_app') THEN
        EXECUTE 'GRANT USAGE ON SCHEMA public TO pci_app';

        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON knowledge_objects TO pci_app';
        EXECUTE 'GRANT SELECT ON tenants TO pci_app';

        -- Append-only: no UPDATE, no DELETE.
        EXECUTE 'GRANT SELECT, INSERT ON knowledge_object_versions TO pci_app';
        EXECUTE 'GRANT SELECT, INSERT ON provenance_records TO pci_app';
        EXECUTE 'GRANT SELECT, INSERT ON audit_records TO pci_app';
        EXECUTE 'GRANT SELECT, INSERT ON events TO pci_app';

        -- Relationships may be removed; that removal is itself audited.
        EXECUTE 'GRANT SELECT, INSERT, DELETE ON relationships TO pci_app';

        -- Explicitly revoke the destructive privileges on Knowledge Objects. Retirement is a
        -- lifecycle transition, never a delete (canonical-object-schema.md invariant 1).
        EXECUTE 'REVOKE DELETE ON knowledge_objects FROM pci_app';
        EXECUTE 'REVOKE UPDATE, DELETE ON knowledge_object_versions FROM pci_app';
        EXECUTE 'REVOKE UPDATE, DELETE ON provenance_records FROM pci_app';
        EXECUTE 'REVOKE UPDATE, DELETE ON audit_records FROM pci_app';
        EXECUTE 'REVOKE UPDATE, DELETE ON events FROM pci_app';
    ELSE
        RAISE NOTICE 'Role pci_app not present; skipping grants. Create it before running the service.';
    END IF;
END
$$;
